-- 001_init.sql — schema iniziale su PostgreSQL.
-- Equivale allo schema SQLite finale (comprese tutte le vecchie "migrazioni"
-- incrementali di db.js), riscritto con i tipi nativi di Postgres:
--   * id            -> integer GENERATED ... AS IDENTITY (al posto di AUTOINCREMENT)
--   * created_at &c -> timestamptz (in UTC; l'API li restituisce nello stesso
--                      formato testuale di prima, "YYYY-MM-DD HH:MM:SS")
--   * date di giorno -> date (l'API le restituisce come "YYYY-MM-DD")
--   * flag 0/1      -> restano integer, per non cambiare il comportamento dell'app

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('patient', 'therapist', 'parent')),
  name text NOT NULL,
  nickname text,
  avatar text DEFAULT '🦊',
  avatar_photo text,
  age_range text,
  age_group text,
  job text,
  goal text,
  goals text,
  bio text,
  specialty text,
  order_number text,
  cv_file text,
  link_code text UNIQUE,
  birth_date date,
  phone text,
  notif_push integer,
  notif_email integer,
  notif_reminders integer,
  notif_morning_time text DEFAULT '08:00',
  notif_lead_min integer DEFAULT 15,
  privacy_accepted_at timestamptz,
  consent_accepted_at timestamptz,
  approved integer DEFAULT 1,
  approval_token text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE patient_therapist (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id integer NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  therapist_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status text DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE parent_child (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  child_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status text DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (parent_id, child_id)
);

CREATE TABLE daily_state (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  date date NOT NULL,
  energy integer, focus integer, stress integer, sleep integer,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, date)
);

CREATE TABLE agenda_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  item_date date NOT NULL,
  time text NOT NULL,
  title text NOT NULL,
  category text NOT NULL,
  status text NOT NULL DEFAULT 'todo',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE agenda_steps (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agenda_item_id integer NOT NULL REFERENCES agenda_items(id) ON DELETE CASCADE,
  text text NOT NULL,
  done integer DEFAULT 0,
  position integer DEFAULT 0
);

CREATE TABLE checkins (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  mood integer, energy integer, focus integer, stress integer, sleep integer, cognitive_load integer,
  mood_label text,
  note text
);

CREATE TABLE messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  therapist_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  sender_role text NOT NULL,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE coach_logs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  category text,
  blocked integer DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE review_slots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  therapist_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  slot_date date NOT NULL,
  slot_time text NOT NULL,
  duration_minutes integer NOT NULL DEFAULT 15,
  cadence text,
  status text NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed', 'confirmed', 'declined', 'cancelled')),
  proposed_by text NOT NULL DEFAULT 'therapist',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE review_requests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id integer NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  therapist_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE diary_answers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  day date NOT NULL,
  answers text NOT NULL DEFAULT '{}',
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, day)
);

CREATE INDEX idx_agenda_user_date ON agenda_items (user_id, item_date);
CREATE INDEX idx_agenda_steps_item ON agenda_steps (agenda_item_id);
CREATE INDEX idx_checkins_user ON checkins (user_id, created_at);
CREATE INDEX idx_messages_pair ON messages (patient_id, therapist_id);
CREATE INDEX idx_review_slots_pair ON review_slots (patient_id, therapist_id);
CREATE INDEX idx_coach_logs_user ON coach_logs (user_id, category);
